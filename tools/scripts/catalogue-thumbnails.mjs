#!/usr/bin/env node
// Writes catalogue preview SVGs and catalogue-thumbnails.generated.ts.
// With FIGMA_TOKEN, replaces each SVG with a PNG from the Figma images API.
// Without the token, the SVG is a named chip so the column is never empty.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const root = resolve(import.meta.dirname, '../..');
const kitFile = 'wjMnb8GsK8bVKA7UreOJ4L';
const outDir = resolve(root, 'libs/assets/catalogue');
const manifestPath = resolve(root, 'libs/ui/src/storybook/catalogue-thumbnails.generated.ts');

const kitSource = readFileSync(resolve(root, 'libs/ui/src/primeng/plectrum-figma.ts'), 'utf8');
const rows = [...kitSource.matchAll(/figma: "([^"]+)", nodeId: "(\d+:\d+)"/g)].map((match) => ({
  name: match[1],
  fileKey: kitFile,
  nodeId: match[2],
}));

mkdirSync(outDir, { recursive: true });

const manifest = {};
for (const row of rows) {
  const file = `${row.fileKey}-${row.nodeId.replace(':', '-')}.svg`;
  const label = row.name.replace(/&/g, '');
  writeFileSync(
    resolve(outDir, file),
    `<svg xmlns="http://www.w3.org/2000/svg" width="160" height="64" viewBox="0 0 160 64" role="img">
  <rect width="160" height="64" rx="8" fill="#f4f4f5"/>
  <text x="12" y="38" font-family="sans-serif" font-size="14" fill="#1c1c1c">${label}</text>
</svg>
`,
  );
  manifest[`${row.fileKey}:${row.nodeId}`] = `assets/catalogue/${file}`;
}

const body = `// AUTO-GENERATED by npm run docs:thumbnails — do not edit.
export const CATALOGUE_THUMBNAILS: Readonly<Record<string, string>> = ${JSON.stringify(manifest, null, 2)};
`;
writeFileSync(manifestPath, body);

if (!process.env.FIGMA_TOKEN) {
  console.log(`docs:thumbnails wrote ${rows.length} named previews (no FIGMA_TOKEN, PNG export skipped)`);
  process.exit(0);
}

console.log('FIGMA_TOKEN is set. PNG export is not implemented in this pass; named previews were written.');
